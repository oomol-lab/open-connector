function fredOutput(key: string, description: string) {
  return s.looseObject(
    "FRED records with revision-window and pagination metadata.",
    {
      realtime_start: s.string("The returned real-time window start date."),
      realtime_end: s.string("The returned real-time window end date."),
      count: s.integer("The total number of matching records."),
      offset: s.integer("The offset of this page."),
      limit: s.integer("The page size."),
      [key]: s.array(
        description,
        key === "vintage_dates"
          ? s.string("A date when observations were first published or revised.")
          : s.looseObject("An upstream FRED record with additional fields preserved."),
      ),
    },
    { required: [] },
  );
}

